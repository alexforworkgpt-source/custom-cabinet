import type { InstructionSummary } from './instructions';
import { instructionSummaries } from './instructions';

export interface InstructionStep {
  id: string;
  heading: string;
  body: string;
  caption: string;
  group?: string;
  optional?: boolean;
}

export interface InstructionScenario {
  id: string;
  title: string;
  summary: string;
}

export interface InstructionArticle extends InstructionSummary {
  intro: string;
  notice: string;
  steps: InstructionStep[];
  scenarios?: InstructionScenario[];
}

const summary = (slug: string): InstructionSummary => {
  const value = instructionSummaries.find((item) => item.slug === slug);
  if (!value) throw new Error(`Missing instruction summary: ${slug}`);
  return value;
};

